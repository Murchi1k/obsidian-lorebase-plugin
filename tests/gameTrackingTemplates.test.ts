import { describe, expect, it } from 'vitest';
import { DEFAULT_SETTINGS } from '../src/constants';
import { GameService } from '../src/services/GameService';
import { MetadataService } from '../src/services/MetadataService';
import { buildSimpleTemplate, getDefaultTemplateFields, renderTemplate } from '../src/services/integrations/templateUtils';
import { getTemplateYamlKeys, orderTemplateContent } from '../src/services/integrations/templateSchema';
import { parseTemplateFieldAliases } from '../src/services/media/templateFieldAliases';
import { enableGameTrackingTemplateFields } from '../src/services/integrations/templatePreferences';
import { createMockApp, createMockFile } from './helpers/testHelpers';

const fields = ['progressPercent', 'achievementsUnlocked', 'achievementsTotal', 'gameModes'];
describe('game tracking template settings', () => {
    it('enables tracking by default for fresh installations and upgrades an existing reduced selection once', () => {
        const fresh = DEFAULT_SETTINGS.integrations.media.games;
        expect(fresh.templateFields).toEqual(expect.arrayContaining(fields));
        for (const key of ['progress_percent', 'achievements_unlocked', 'achievements_total', 'game_modes']) expect(getTemplateYamlKeys(fresh.template)).toContain(key);
        const config = structuredClone(fresh);
        config.templateFields = ['status', 'playtime', 'name'];
        config.templateMode = 'simple'; config.fieldAliases = { progress_percent: 'MyProgress' };
        enableGameTrackingTemplateFields(config);
        expect(config.templateFields).toEqual(['status', 'playtime', ...fields, 'name']);
        expect(config.templateFields).not.toContain('genres');
        expect(config.template).toContain('MyProgress: {{VALUE:progressPercent}}');
        const before = structuredClone(config);
        enableGameTrackingTemplateFields(config);
        expect(config).toEqual(before);
    });
    it('adds only missing tracking properties to an older advanced template and keeps its body and renamed progress', () => {
        const config = structuredClone(DEFAULT_SETTINGS.integrations.media.games);
        config.templateMode = 'advanced'; config.templateFields = ['name'];
        config.template = '---\nMyProgress: {{VALUE:progressPercent}}\ncustom: keep\n---\n\n## My Notes\nPersonal text';
        enableGameTrackingTemplateFields(config);
        expect(config.template).toContain('MyProgress: {{VALUE:progressPercent}}');
        expect(config.template).not.toContain('progress_percent:');
        expect(config.template).toContain('achievements_unlocked: {{VALUE:achievementsUnlocked}}');
        expect(config.template).toContain('game_modes: {{VALUE:gameModes}}');
        expect(config.template).not.toContain('poster:');
        expect(config.template).toContain('custom: keep');
        expect(config.template.endsWith('## My Notes\nPersonal text')).toBe(true);
        expect(config.advancedTemplate).toBe(config.template);
        const before = config.template;
        enableGameTrackingTemplateFields(config);
        expect(config.template).toBe(before);
    });
    it('exposes the new fields, renders typed values and respects a reduced selection', () => {
        expect(getDefaultTemplateFields('games')).toEqual(expect.arrayContaining(fields));
        const template = buildSimpleTemplate('games', ['playtime', ...fields]);
        expect(getTemplateYamlKeys(template)).toEqual(['playtime', 'progress_percent', 'achievements_unlocked', 'achievements_total', 'game_modes']);
        const rendered = renderTemplate(template, { playtime: 10807, progressPercent: 25, achievementsUnlocked: 3, achievementsTotal: 30, gameModes: ['solo', 'coop'] });
        expect(rendered).toContain('progress_percent: 25');
        expect(rendered).toContain('playtime: 10807');
        expect(rendered).toContain('game_modes: ["solo","coop"]');
        expect(rendered).not.toContain('{{VALUE:');
        expect(getTemplateYamlKeys(buildSimpleTemplate('games', ['status']))).toEqual(['status']);
    });
    it('does not invent progress, time or achievements for newly created notes and retains real zero values in compact mode', () => {
        const template = buildSimpleTemplate('games', ['playtime', ...fields]);
        const empty = renderTemplate(template, {});
        for (const key of ['playtime', 'progress_percent', 'achievements_unlocked', 'achievements_total']) expect(empty).toContain(`${key}: null`);
        const compact = orderTemplateContent(renderTemplate(template, { progressPercent: 0, achievementsUnlocked: 0, gameModes: [] }), template, { compact: true });
        expect(compact).toContain('progress_percent: 0');
        expect(compact).toContain('achievements_unlocked: 0');
        expect(compact).not.toContain('playtime:');
        expect(compact).not.toContain('achievements_total:');
        expect(compact).not.toContain('game_modes:');
    });
    it.each(['simple', 'advanced'] as const)('reads and edits renamed tracking properties in %s mode without duplicating canonical keys', async mode => {
        const settings = structuredClone(DEFAULT_SETTINGS);
        const templateSettings = settings.integrations.media.games;
        templateSettings.templateEnabled = true; templateSettings.templateMode = mode;
        templateSettings.templateFields = ['type', 'name', 'playtime', ...fields];
        templateSettings.fieldAliases = { progress_percent: 'MyProgress', playtime: 'Minutes', achievements_unlocked: 'Unlocked', achievements_total: 'All', game_modes: 'Modes' };
        templateSettings.template = buildSimpleTemplate('games', templateSettings.templateFields, templateSettings.fieldAliases);
        const aliases = parseTemplateFieldAliases('game', templateSettings.template);
        expect(aliases.progress_percent).toBe('MyProgress');
        expect(aliases.game_modes).toBe('Modes');
        const file = createMockFile('Games/Example.md', 'Example');
        const fm: Record<string, unknown> = { type: 'game', name: 'Example', MyProgress: 60, Minutes: 180, Unlocked: 3, All: 30, Modes: ['solo'], custom: 'keep' };
        const app = createMockApp({ [file.path]: { frontmatter: fm } });
        app.vault.getAbstractFileByPath = () => file;
        app.fileManager.processFrontMatter = async (_file, handler) => handler(fm);
        const metadata = new MetadataService(app, () => settings);
        const service = new GameService(app, metadata);
        const item = service.parseGameFromCache(file)!;
        expect(item).toMatchObject({ progressPercent: 60, playtimeMinutes: 180, achievementsUnlocked: 3, achievementsTotal: 30, gameModes: ['solo'] });
        await service.updateGame(item, { playtimeMinutes: 125, achievementsUnlocked: 4, gameModes: ['coop'] });
        expect(fm).toMatchObject({ MyProgress: 60, Minutes: 125, Unlocked: 4, All: 30, Modes: ['coop'], custom: 'keep' });
        await metadata.updateMetadata(file, { playtime: 0, achievements_unlocked: 0, achievements_total: 78 }, 'game');
        expect(fm).toMatchObject({ MyProgress: 60, Minutes: 0, Unlocked: 0, All: 78, Modes: ['coop'] });
        expect(service.parseGameFromCache(file)).toMatchObject({ progressPercent: 60, playtimeMinutes: 0, achievementsUnlocked: 0, achievementsTotal: 78 });
        for (const key of ['progress_percent', 'playtime', 'achievements_unlocked', 'achievements_total', 'game_modes']) expect(fm).not.toHaveProperty(key);
    });
});
