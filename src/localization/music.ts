export type MusicTextKey = keyof typeof strings;
export function mt(key: MusicTextKey | import('../types').CustomMediaStatus): string {
    if (key.startsWith('custom_')) return getStatusAppearance('music', key as import('../types').CustomMediaStatus).label || key;
    const textKey = key as MusicTextKey;
    return strings[textKey][({ en: 0, ru: 1, uk: 2, 'zh-CN': 3 } as const)[i18n.getLanguage()] ?? 0];
}
